-- ═══════════════════════════════════════════════════════════════════
-- إضافة عمود «وقت التحويل» لجدول البلاغات
-- ═══════════════════════════════════════════════════════════════════
-- الغرض: تخزين اللحظة الدقيقة التي حُوّل فيها البلاغ للموظف،
--        يستخدمه تطبيق تحويل البلاغات بالجوال (‎/transfer‎).
--
-- طريقة التشغيل:
--   لوحة تحكم Supabase ← SQL Editor ← الصق الأمر التالي ← Run
--
-- ملاحظة: واجهة ‎/api/transfer‎ تعمل حتى قبل تنفيذ هذا الأمر
--         (تحفظ البلاغ بدون وقت التحويل تلقائياً)، لكن يُفضّل تنفيذه
--         للحصول على السجل الزمني الكامل.
-- ═══════════════════════════════════════════════════════════════════

ALTER TABLE public.tickets
  ADD COLUMN IF NOT EXISTS transferred_at timestamptz;

COMMENT ON COLUMN public.tickets.transferred_at IS 'وقت تحويل البلاغ للموظف (يُسجَّل تلقائياً من تطبيق التحويل بالجوال)';

-- فهرس يسرّع الترتيب حسب وقت التحويل في السجلات والتقارير
CREATE INDEX IF NOT EXISTS tickets_transferred_at_idx
  ON public.tickets (transferred_at DESC);
